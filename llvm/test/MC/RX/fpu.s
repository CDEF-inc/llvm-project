# RUN: llvm-mc -triple=rx-none-elf -mcpu=rxv1 -show-encoding %s \
# RUN:   | FileCheck %s
# RUN: llvm-mc -triple=rx-none-elf -mcpu=rxv3e -show-encoding %s \
# RUN:   | FileCheck %s

# Single-precision FPU instructions (RXv1, plus the RXv2 additions).
# The encodings match GNU as 2.43 (rx-elf).
fadd r1, r2
# CHECK: fadd r1, r2 ; encoding: [0xfc,0x8b,0x12]
fsub r15, r0
# CHECK: fsub r15, r0 ; encoding: [0xfc,0x83,0xf0]
fmul r3, r4
# CHECK: fmul r3, r4 ; encoding: [0xfc,0x8f,0x34]
fdiv r5, r6
# CHECK: fdiv r5, r6 ; encoding: [0xfc,0x93,0x56]
fcmp r7, r8
# CHECK: fcmp r7, r8 ; encoding: [0xfc,0x87,0x78]
ftoi r9, r10
# CHECK: ftoi r9, r10 ; encoding: [0xfc,0x97,0x9a]
round r11, r12
# CHECK: round r11, r12 ; encoding: [0xfc,0x9b,0xbc]
itof r13, r14
# CHECK: itof r13, r14 ; encoding: [0xfc,0x47,0xde]
fadd [r1], r2
# CHECK: fadd [r1], r2 ; encoding: [0xfc,0x88,0x12]
fadd 0[r1], r2
# CHECK: fadd [r1], r2 ; encoding: [0xfc,0x88,0x12]
fadd [r1].l, r2
# CHECK: fadd [r1], r2 ; encoding: [0xfc,0x88,0x12]
fadd 4[r1], r2
# CHECK: fadd 4[r1], r2 ; encoding: [0xfc,0x89,0x12,0x01]
fadd 4[r1].L, r2
# CHECK: fadd 4[r1], r2 ; encoding: [0xfc,0x89,0x12,0x01]
fadd 1020[r15], r0
# CHECK: fadd 1020[r15], r0 ; encoding: [0xfc,0x89,0xf0,0xff]
fadd 1024[r1], r2
# CHECK: fadd 1024[r1], r2 ; encoding: [0xfc,0x8a,0x12,0x00,0x01]
fadd 262140[r1], r2
# CHECK: fadd 262140[r1], r2 ; encoding: [0xfc,0x8a,0x12,0xff,0xff]
fsub [r2], r3
# CHECK: fsub [r2], r3 ; encoding: [0xfc,0x80,0x23]
fsub 8[r2], r3
# CHECK: fsub 8[r2], r3 ; encoding: [0xfc,0x81,0x23,0x02]
fsub 2000[r2], r3
# CHECK: fsub 2000[r2], r3 ; encoding: [0xfc,0x82,0x23,0xf4,0x01]
fmul [r3], r4
# CHECK: fmul [r3], r4 ; encoding: [0xfc,0x8c,0x34]
fmul 12[r3], r4
# CHECK: fmul 12[r3], r4 ; encoding: [0xfc,0x8d,0x34,0x03]
fmul 4096[r3], r4
# CHECK: fmul 4096[r3], r4 ; encoding: [0xfc,0x8e,0x34,0x00,0x04]
fdiv [r4], r5
# CHECK: fdiv [r4], r5 ; encoding: [0xfc,0x90,0x45]
fdiv 16[r4], r5
# CHECK: fdiv 16[r4], r5 ; encoding: [0xfc,0x91,0x45,0x04]
fdiv 65532[r4], r5
# CHECK: fdiv 65532[r4], r5 ; encoding: [0xfc,0x92,0x45,0xff,0x3f]
fcmp [r5], r6
# CHECK: fcmp [r5], r6 ; encoding: [0xfc,0x84,0x56]
fcmp 20[r5], r6
# CHECK: fcmp 20[r5], r6 ; encoding: [0xfc,0x85,0x56,0x05]
fcmp 1028[r5], r6
# CHECK: fcmp 1028[r5], r6 ; encoding: [0xfc,0x86,0x56,0x01,0x01]
ftoi [r6], r7
# CHECK: ftoi [r6], r7 ; encoding: [0xfc,0x94,0x67]
ftoi 24[r6], r7
# CHECK: ftoi 24[r6], r7 ; encoding: [0xfc,0x95,0x67,0x06]
ftoi 8000[r6], r7
# CHECK: ftoi 8000[r6], r7 ; encoding: [0xfc,0x96,0x67,0xd0,0x07]
round [r7], r8
# CHECK: round [r7], r8 ; encoding: [0xfc,0x98,0x78]
round 28[r7], r8
# CHECK: round 28[r7], r8 ; encoding: [0xfc,0x99,0x78,0x07]
round 4000[r7], r8
# CHECK: round 4000[r7], r8 ; encoding: [0xfc,0x9a,0x78,0xe8,0x03]
fadd #0, r1
# CHECK: fadd #0, r1 ; encoding: [0xfd,0x72,0x21,0x00,0x00,0x00,0x00]
fadd #0x3f800000, r1

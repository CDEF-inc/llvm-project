fsub #0xbf800000, r15
# CHECK: fsub #3212836864, r15 ; encoding: [0xfd,0x72,0x0f,0x00,0x00,0x80,0xbf]
fmul #0x40000000, r2
# CHECK: fmul #1073741824, r2 ; encoding: [0xfd,0x72,0x32,0x00,0x00,0x00,0x40]

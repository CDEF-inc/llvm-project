#ifndef LLVM_LIB_TARGET_RX_RXSUBTARGET_H
#define LLVM_LIB_TARGET_RX_RXSUBTARGET_H

#include "RXFrameLowering.h"
#include "RXISelLowering.h"
#include "RXInstrInfo.h"
#include "RXRegisterInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <memory>
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "RXGenSubtargetInfo.inc"

namespace llvm {

class StringRef;

class RXSubtarget : public RXGenSubtargetInfo {
  virtual void anchor();

  bool HasRXv2 = false;
  bool HasRXv3 = false;
  bool HasRXv3e = false;
  bool HasDFPU = false;
  bool Has64BitDoubles = false;

  RXInstrInfo InstrInfo;
  RXFrameLowering FrameLowering;
  RXTargetLowering TLInfo;
  std::unique_ptr<const SelectionDAGTargetInfo> TSInfo;

public:
  RXSubtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
              const TargetMachine &TM);
  ~RXSubtarget() override;

  RXSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  /// Parses features string setting specified subtarget options. Definition
  /// of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  bool hasRXv2() const { return HasRXv2; }
  bool hasRXv3() const { return HasRXv3; }
  bool hasRXv3e() const { return HasRXv3e; }
  bool hasDFPU() const { return HasDFPU; }
  bool has64BitDoubles() const { return Has64BitDoubles; }

  const RXInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const RXFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const RXRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const RXTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override;
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_RX_RXSUBTARGET_H

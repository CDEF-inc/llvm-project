#ifndef LLVM_LIB_TARGET_RX_MCTARGETDESC_RXINSTPRINTER_H
#define LLVM_LIB_TARGET_RX_MCTARGETDESC_RXINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class RXInstPrinter : public MCInstPrinter {
public:
  RXInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

  void printRegName(raw_ostream &OS, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

private:
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  // Displacement of "dsp[Rn]": printed without '#'.
  void printDisp(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  // Branch target: a label, or a displacement from the instruction.
  void printPCRel(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printPCRel(const MCInst *MI, uint64_t Address, unsigned OpNo,
                  raw_ostream &O) {
    printPCRel(MI, OpNo, O);
  }
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_RX_MCTARGETDESC_RXINSTPRINTER_H
